const discord = require("discord.js");

const Canvas = require('skia-canvas');

const OptionType = require('../../util/optiontype.js');
const SkiaCanvasUtil = require('../../util/canvas-util-skia.js');

const BaseCommand = require("../../classes/basecommand.js");

class Command extends BaseCommand {
    constructor() {
        super();
        this.name = "hired";
        this.description = "You are hired!";
        this.descriptionLong = "You are hired!"
            + "\n" + "Places your image onto a backdrop stating they are hired.";
        this.attributes = {
            unlisted: false,
            permission: 0,
            lockedToCommands: true,
        };
    }

    async invoke(message, args, util) {
        const [imageBuffer] = await util.getInputImagesForCommand();
        if (!imageBuffer) return;

        const nameToDisplay = args.join(" ") || (message.member ? message.member.displayName : message.author.username);
        const userImage = await Canvas.loadImage(imageBuffer);
        const backdrop = await Canvas.loadImage('assets/hired.png');

        const canvas = new Canvas.Canvas(backdrop.width, backdrop.height);
        const ctx = canvas.getContext("2d");
        ctx.drawImage(backdrop, 0, 0);
        ctx.drawImage(userImage, 274, 30, 291, 542);

        ctx.font = "72px Sans";
        ctx.fillStyle = "white";
        ctx.textAlign = "center";
        ctx.textBaseline = "top";
        SkiaCanvasUtil.fillText(ctx, nameToDisplay, 123, 279, 229);

        // Convert the canvas to a Discord attachment
        const buffer = await canvas.toBuffer("image/png");
        const attachment = new discord.MessageAttachment(buffer, 'hired.png');
        message.reply({
            content: `-# Generated by <@${message.author.id}>`,
            files: [attachment]
        });
    }
}

// needs to do new Command() in index.js because typing static every time STINKS!
module.exports = Command;